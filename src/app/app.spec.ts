import { TestBed } from '@angular/core/testing';
import { App } from './app';

describe('App', () => {
  beforeEach(async () => {
    await TestBed.configureTestingModule({
      imports: [App],
    }).compileComponents();
  });

  it('should create the app', () => {
    const fixture = TestBed.createComponent(App);
    expect(fixture.componentInstance).toBeTruthy();
  });

  it('should render the JSON formatter component', async () => {
    const fixture = TestBed.createComponent(App);
    await fixture.whenStable();
    const compiled = fixture.nativeElement as HTMLElement;

    expect(compiled.querySelector('app-json-formatter')).toBeTruthy();
    expect(compiled.querySelector('.workspace')).toBeTruthy();
    expect(compiled.querySelector('textarea')).toBeTruthy();
    expect(compiled.querySelector('app-json-node')).toBeTruthy();
  });
});
